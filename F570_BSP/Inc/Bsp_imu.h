#ifndef __BSP_IMU_H
#define __BSP_IMU_H

#include "main.h"
#include "attitude_common.h"
#include <stdint.h>


/*
 * ============================================================
 * 三轴数据
 * ============================================================
 */
typedef struct
{
    float x;
    float y;
    float z;

} IMU_AXIS_T;


/*
 * ============================================================
 * IMU数据结构
 * ============================================================
 */
typedef struct
{
    IMU_AXIS_T accel;
    IMU_AXIS_T gyro;

} IMU_DATA_T;


/*
 * ============================================================
 * 姿态角结构体
 * ============================================================
 */
typedef struct
{
    float roll;
    float pitch;
    float yaw;

} ATTITUDE_DATA_T;


/*
 * ============================================================
 * 传感器自身固定零偏
 * ============================================================
 */
extern IMU_DATA_T ZreoPoint;


/*
 * ============================================================
 * 传感器+机架安装角度偏差
 * ============================================================
 */
extern ATTITUDE_DATA_T ZeroAttitude;


/*
 * ============================================================
 * 初始化ICM20948
 * ============================================================
 */
uint8_t ICM20948_Init(I2C_HandleTypeDef *hi2c);


/*
 * ============================================================
 * 读取ICM20948
 * ============================================================
 */
uint8_t ICM20948_Update(IMU_DATA_T *data,
                        I2C_HandleTypeDef *hi2c);

#endif
